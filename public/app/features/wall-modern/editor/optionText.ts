export function wallOptionText(text?: string): string {
  if (!text) {
    return text ?? '';
  }
  if (vocabulary[text]) {
    return vocabulary[text];
  }
  const override = /^Override (\d+)$/.exec(text);
  if (override) {
    return `필드별 설정 ${override[1]}`;
  }
  return text;
}

export function wallOptionChoices<T extends { label?: string; description?: string }>(options: T[]): T[] {
  return options.map((option) => ({
    ...option,
    label: wallOptionText(option.label),
    description: option.description ? wallOptionText(option.description) : undefined,
  }));
}

export function useWallOptionText() {
  const wall = useContext(editorPresentationContext);
  return wall ? wallOptionText : (text?: string) => text ?? '';
}

